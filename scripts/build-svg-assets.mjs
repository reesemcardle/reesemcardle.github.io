import { createReadStream } from "node:fs";
import { mkdir, stat, writeFile } from "node:fs/promises";
import { createServer } from "node:http";
import { createRequire } from "node:module";
import { extname, join, normalize, resolve, sep } from "node:path";
import "./build-water-maps.mjs";

const port = 8010;
const baseUrl = `http://127.0.0.1:${port}`;
const rootDir = resolve(".");
const outputDir = resolve("content/svg");

const playwright = loadPlaywright();
const server = await startServer();

try {
  await mkdir(outputDir, { recursive: true });

  const browser = await playwright.chromium.launch({
    headless: true,
    executablePath: process.env.PLAYWRIGHT_CHROME_PATH || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
  });
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });

  await page.goto(`${baseUrl}/`, { waitUntil: "networkidle" });
  await page.waitForSelector("#rideGhosts path");
  await writeSvg("cycling-basemap.svg", await snapshotSvg(page, "#cyclingVisual", {
    remove: [".ride-layer"]
  }));
  await writeSvg("cycling-traces.svg", await snapshotSvg(page, "#cyclingVisual", {
    remove: [".paper", ".paper-grain", ".map-layer", "#rideReplayBase", "#ridePath", "#ridePoint"]
  }));

  await page.goto(`${baseUrl}/?mode=sailing`, { waitUntil: "networkidle" });
  await page.waitForSelector("#sailingVisual:not([hidden])");
  await page.waitForSelector("#sailGhosts path");
  await writeSvg("sailing-traces.svg", await snapshotSvg(page, "#sailingVisual", {
    remove: [".paper", ".paper-grain", ".map-layer", "#sailReplayBase", "#sailPath", "#sailPoint"]
  }));

  await page.goto(`${baseUrl}/?mode=archery`, { waitUntil: "networkidle" });
  await page.waitForSelector(".target-band-10");
  await writeSvg("archery-target.svg", await snapshotSvg(page, "#archeryVisual", {
    remove: ["#archeryShots"]
  }));

  await browser.close();
} finally {
  await new Promise((resolveClose) => server.close(resolveClose));
}

async function snapshotSvg(page, selector, { remove = [] } = {}) {
  return page.evaluate(({ selector, remove }) => {
    const source = document.querySelector(selector);
    if (!source) throw new Error(`Missing ${selector}`);

    const clone = source.cloneNode(true);
    clone.removeAttribute("hidden");
    clone.removeAttribute("style");
    clone.setAttribute("xmlns", "http://www.w3.org/2000/svg");
    const computedStyle = getComputedStyle(source);
    const cameraProperties = [
      "--map-pitch",
      "--map-scale",
      "--map-shift-x",
      "--map-shift-y",
      "--map-perspective"
    ];
    cameraProperties.forEach((property) => {
      const value = computedStyle.getPropertyValue(property).trim();
      if (value) clone.style.setProperty(property, value);
    });

    remove.forEach((pattern) => {
      clone.querySelectorAll(pattern).forEach((element) => element.remove());
    });

    clone.querySelectorAll("[hidden]").forEach((element) => element.removeAttribute("hidden"));
    const style = document.createElementNS("http://www.w3.org/2000/svg", "style");
    style.textContent = collectLocalCss();
    clone.insertBefore(style, clone.firstChild);

    return `<!-- Generated by scripts/build-svg-assets.mjs. Edit styles in styles.css or regenerate from source data. -->\n${clone.outerHTML}\n`;

    function collectLocalCss() {
      return [...document.styleSheets].map((sheet) => {
        try {
          return [...sheet.cssRules].map((rule) => rule.cssText).join("\n");
        } catch {
          return "";
        }
      }).filter(Boolean).join("\n");
    }
  }, { selector, remove });
}

async function writeSvg(filename, svg) {
  await writeFile(join(outputDir, filename), svg);
  console.log(`wrote content/svg/${filename}`);
}

function loadPlaywright() {
  const require = createRequire(import.meta.url);
  try {
    return require("playwright");
  } catch (localError) {
    const bundledModules = `${process.env.HOME}/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules`;
    try {
      return createRequire(`${bundledModules}/`)("playwright");
    } catch (bundledError) {
      throw new Error(`Playwright is not available locally or in the Codex runtime.\n${localError.message}\n${bundledError.message}`);
    }
  }
}

async function startServer() {
  const server = createServer(async (request, response) => {
    const requestUrl = new URL(request.url || "/", baseUrl);
    const filePath = resolveRequestPath(requestUrl.pathname);

    if (!filePath) {
      response.writeHead(403);
      response.end("Forbidden");
      return;
    }

    try {
      const fileStat = await stat(filePath);
      if (!fileStat.isFile()) {
        response.writeHead(404);
        response.end("Not found");
        return;
      }

      response.writeHead(200, { "content-type": contentType(filePath) });
      if (request.method === "HEAD") {
        response.end();
      } else {
        createReadStream(filePath).pipe(response);
      }
    } catch {
      response.writeHead(404);
      response.end("Not found");
    }
  });

  await new Promise((resolveReady, rejectReady) => {
    server.once("error", rejectReady);
    server.listen(port, "127.0.0.1", resolveReady);
  });
  return server;
}

function resolveRequestPath(pathname) {
  const decoded = decodeURIComponent(pathname);
  const normalized = normalize(decoded === "/" ? "/index.html" : decoded);
  const filePath = join(rootDir, normalized);
  return filePath === rootDir || filePath.startsWith(`${rootDir}${sep}`) ? filePath : null;
}

function contentType(filePath) {
  return {
    ".css": "text/css",
    ".gpx": "application/gpx+xml",
    ".html": "text/html",
    ".js": "text/javascript",
    ".json": "application/json",
    ".mjs": "text/javascript",
    ".svg": "image/svg+xml"
  }[extname(filePath)] || "application/octet-stream";
}
